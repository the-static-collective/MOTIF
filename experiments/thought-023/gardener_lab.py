def evaluate_advice(advice,*,source='UNVERIFIED_ADVICE_NOT_MODEL_EXECUTION'):
    checked=validate_advice(advice)
    report=proof_report(checked['extension'])
    # executable code is generated by a trusted fixed template only if the
    # extension passes the independently conducted finite synthesis/audit.
    compiled=None
    if report['new_invert_status']=='REVIEW_CANDIDATE_NOT_INSTALLED':
        compiled=execute_source(report['new_invert_expression'],checked['extension'])
        got=compiled.pop('results')
        good=sum(got[a*8+b]==independent_oracle('invert',a,b) for a in range(8) for b in range(8))
        compiled['passed']=good;compiled['total']=64
        if good!=64:raise GrammarError('executable evaluator contradiction')
    output={'schema':SCHEMA,'source':source,'advice':checked,'report':report,
            'executable_audit':compiled,
            'stage':'CANDIDATE_GRAMMAR_FOR_HUMAN_REVIEW_NOT_INSTALLED' if compiled else 'HOLD_GRAMMAR_NOT_IMPROVED',
            'model_authored_python_executed':False,'llm_invocations_during_this_offline_run':0,
            'grammar_installed':False,'installed':False,'external_authority':'NONE'}
    output['receipt_digest']=digest(output)
    return output


def ablations():
    """Source-owned controls; no label pretending these are model suggestions."""
    result={extension:proof_report(extension) for extension in EXTENSIONS}
    orig=result['none']
    for ext,x in result.items():
        assert x['original_invert_status']==orig['original_invert_status']
        assert x['old_functions_preserved']==orig['expanded_grammar_functions']
    data={'schema':'motif.thought023.source-owned-ablation.v1',
          'controls':result,
          'alternatives_tested_independently':['none','empty_constant','universe_constant','set_complement'],
          'explanation':('Only the restricted typed syntax changes. These controls assess closure and '
            'program expressivity, not a blind model discovery. The fixed task family is author-designed.'),
          'model_called':False,'grammar_installed':False,'installed':False,'external_authority':'NONE'}
    data['receipt_digest']=digest(data)
    return data


