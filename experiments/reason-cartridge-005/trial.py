"""Executable trial: defend a theorem, correct an invalid premise, stop looping.

All 'observations' are generated by explicit local fixture owners.  No
external searches, communication, or actions are performed.
"""
import json
from engine import (Objection, ToyOwner, Model, owner4, build_record, hashed)
from critic import Critic, Receiver, Memory


def redundant():
    return owner4.Inquiry(
        ("S","A","B","T"),
        (("S","A"),("A","T"),("S","B"),("B","T"),("S","T")),
        (("S","A","PRESENT","w1"),("A","T","PRESENT","w2"),
         ("S","B","PRESENT","w3"),("B","T","PRESENT","w4")),
        ("S","T"),True)


def fragile():
    return owner4.Inquiry(
        ("S","A","T"), (("S","A"),("A","T"),("S","T")),
        (("S","A","PRESENT","w1"),("A","T","PRESENT","w2")),
        ("S","T"),True)


def false_negative():
    return owner4.Inquiry(
        ("S","A","T"), (("S","A"),("A","T"),("S","T")),
        (("S","A","PRESENT","w1"),("A","T","ABSENT","w2")),
        ("S","T"),True)


def heldout():
    strong=owner4.Inquiry(
        ("S","X","Y","T"),(("S","X"),("X","T"),("S","Y"),("Y","T"),("S","T")),
        (("S","X","PRESENT","r1"),("X","T","PRESENT","r2"),
         ("S","Y","PRESENT","r3"),("Y","T","PRESENT","r4")),
        ("S","T"),True)
    weak=owner4.Inquiry(
        ("S","X","T"),(("S","X"),("X","T"),("S","T")),
        (("S","X","PRESENT","r1"),("X","T","PRESENT","r2")),
        ("S","T"),True)
    denied=owner4.Inquiry(
        ("S","X","T"),(("S","X"),("X","T"),("S","T")),
        (("S","X","ABSENT","r1"),("X","T","ABSENT","r2")),
        ("S","T"),True)
    false=owner4.Inquiry(
        ("S","X","T"),(("S","X"),("X","T"),("S","T")),
        (("S","X","PRESENT","r1"),("X","T","ABSENT","r2")),
        ("S","T"),True)
    return (
        (strong,Objection("held-strong","RETRACT_PRESENT",(("S","X"),)),"DEFENSE"),
        (weak,Objection("held-weak","RETRACT_PRESENT",(("X","T"),)),"MATERIAL_OBJECTION"),
        (denied,Objection("held-neg","REVIEW_ABSENCE",(("X","T"),)),"DEFENSE"),
        (false,Objection("held-neg-weak","REVIEW_ABSENCE",(("X","T"),)),"MATERIAL_OBJECTION"),
    )


def run():
    sturdy=redundant()
    red=Critic(sturdy,(
        Objection("cosmetic-a","RETRACT_PRESENT",(("S","A"),)),
        Objection("cosmetic-b","RETRACT_PRESENT",(("B","T"),)),
    )).run()
    assert red["owner_reviews"] == 0 and len(red["proof_defenses"]) == 2

    fr=fragile()
    challenge=Objection("source-check","RETRACT_PRESENT",(("A","T"),))
    correction_owner=ToyOwner("fragile-source", {("A","T"):False})
    correction=Critic(fr,(challenge,)).run(correction_owner)
    assert correction["status"] == "CORRECTION"

    false_alarm_owner=ToyOwner("same-source",{("A","T"):True})
    defense=Critic(fr,(challenge,)).run(false_alarm_owner)
    assert defense["status"] == "OWNER_DEFENSE"

    neg=false_negative()
    neg_challenge=Objection("recheck-absence","REVIEW_ABSENCE",(("A","T"),))
    neg_owner=ToyOwner("recovered-source",{("A","T"):True})
    recovered=Critic(neg,(neg_challenge,)).run(neg_owner)
    assert recovered["status"] == "CORRECTION"

    costly_owner=ToyOwner("unneeded-source",{("A","T"):False})
    costly=Critic(fr,(challenge,),model=Model(0.5,6.0,5.0,1.0)).run(costly_owner)
    assert costly["status"]=="STOP_NO_POSITIVE_VALUE" and costly_owner.calls == 0

    board=Receiver(json.dumps(correction["outcome_cartridge"]))
    reviewed=board.preview(heldout())
    if reviewed["errors"] == 0:
        board.admit("ADMIT_READ_ONLY",reviewed["review_digest"])
    suggested=board.suggest()
    cache=Memory()
    key=cache.store(json.dumps(correction["outcome_cartridge"]))
    remembered=cache.recall(fr,challenge)
    not_transferable=cache.recall(neg,challenge)

    return {
        "schema":"motif.reason.meta-objection-trial.v1",
        "redundant_objection_defenses":len(red["proof_defenses"]),
        "redundant_owner_reviews":red["owner_reviews"],
        "real_premise_error_corrections_in_synthetic_fixture":
            sum(x["status"]=="CORRECTION" for x in (correction,recovered)),
        "source_rebuttals_after_fixture_review":
            sum(x["status"]=="OWNER_DEFENSE" for x in (defense,)),
        "costly_probe_avoided":costly["owner_reviews"]==0,
        "meta_critic_source_reviews":sum(x["owner_reviews"] for x in
            (red,correction,defense,recovered,costly)),
        "naive_always_review_count":2+1+1+1+1,
        "cost_model":Model().value(),
        "repaired_positive_claim":correction["outcome_cartridge"]["outcome"]["new_conclusion"],
        "repaired_negative_claim":recovered["outcome_cartridge"]["outcome"]["new_conclusion"],
        "independent_review":{"cases":reviewed["cases"],"errors":reviewed["errors"]},
        "fixture_only_admitted":board.approved,
        "suggestion":suggested,
        "portable_memory_key":key,
        "exact_context_memory_status":remembered["status"],
        "changed_context_memory_status":not_transferable["status"],
        "source_owner_git_blob":correction["outcome_cartridge"]["owner_reason004_blob"],
        "external_observations_performed":0,
        "external_authority":False,
    }


if __name__=="__main__":
    print(json.dumps(run(),indent=2,sort_keys=True))
