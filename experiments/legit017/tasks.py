"""LEGIT-017 independent task families and classical exact/strong baselines.

All tasks are procedurally generated by us, not externally authored and not
unfamiliar to the engineer who wrote these distributions. Training and heldout
identifiers are disjoint and fixed BEFORE selection. Tests never label these
independently blinded or benchmark-general.

Three different engineering problem types:
1. directed graph reachability;
2. finite subset-sum feasibility;
3. substring membership in generated text.

Strong classical reference uses conventional preprocessing where appropriate,
so an index-based generated tool is not unfairly compared only to a weak scan.
"""
from __future__ import annotations
from dataclasses import dataclass
from functools import lru_cache
from random import Random

FAMILIES=("GRAPH","SUBSET","TEXT")
TRAIN_START={"GRAPH":180100,"SUBSET":280100,"TEXT":380100}
TEST_START={"GRAPH":190100,"SUBSET":290100,"TEXT":390100}

@dataclass(frozen=True)
class Task:
    family: str
    identifier: str
    instance: tuple
    queries: tuple

def _graph(seed,queries):
    rng=Random(seed)
    n=18
    edges={(a,b) for a in range(n) for b in range(n)
           if a!=b and rng.randrange(13)<2}
    # Guarantee at least a small number of reachable and unreachable pairs.
    edges.update({(i,i+1) for i in range(0,17,3)})
    edges=tuple(sorted(edges))
    questions=tuple((rng.randrange(n),rng.randrange(n))
                    for _ in range(queries))
    return (n,edges),questions

def _subset(seed,queries):
    rng=Random(seed)
    weights=tuple(rng.randrange(2,24) for _ in range(13))
    total=sum(weights)
    questions=tuple(rng.randrange(0,total+26) for _ in range(queries))
    return weights,questions

def _text(seed,queries):
    rng=Random(seed)
    alphabet="abcdefghi"
    doc="".join(rng.choice(alphabet) for _ in range(900))
    questions=[]
    for i in range(queries):
        width=3+(i%3)
        if i%2:
            start=rng.randrange(0,len(doc)-width+1)
            questions.append(doc[start:start+width])
        else:
            questions.append("".join(rng.choice(alphabet)
                                     for _ in range(width)))
    return (doc,),tuple(questions)

def suite(phase):
    if phase not in ("TRAIN","HELDOUT"):
        raise ValueError("Unregistered task allocation")
    count=6 if phase=="TRAIN" else 12
    q=40 if phase=="TRAIN" else 72
    seedset=TRAIN_START if phase=="TRAIN" else TEST_START
    funcs={"GRAPH":_graph,"SUBSET":_subset,"TEXT":_text}
    tasks=[]
    for family in FAMILIES:
        for k in range(count):
            seed=seedset[family]+k
            instance,queries=funcs[family](seed,q)
            tasks.append(Task(family,f"{phase}_{family}_{seed}",
                              instance,queries))
    return tuple(tasks)

def direct(task,query):
    """Independently coded conventional per-question reference."""
    family=task.family
    if family=="GRAPH":
        n,edges=task.instance
        source,target=query
        adjacency=[[] for _ in range(n)]
        for x,y in edges:
            adjacency[x].append(y)
        seen={source}
        pending=[source]
        while pending:
            node=pending.pop()
            if node==target:return True
            for nxt in adjacency[node]:
                if nxt not in seen:
                    seen.add(nxt)
                    pending.append(nxt)
        return False
    if family=="SUBSET":
        weights=task.instance
        target=query
        if target<0:return False
        @lru_cache(None)
        def find(i,rest):
            if rest==0:return True
            if rest<0 or i==len(weights):return False
            return find(i+1,rest) or find(i+1,rest-weights[i])
        return find(0,target)
    if family=="TEXT":
        (text,)=task.instance
        return query in text
    raise ValueError("Unknown task family")

def strong_build(task):
    """Separate strongest obvious exact classical preprocessing per family."""
    if task.family=="GRAPH":
        n,edges=task.instance
        out=[set() for _ in range(n)]
        for a,b in edges:out[a].add(b)
        closure=[]
        for start in range(n):
            visited={start}
            todo=[start]
            while todo:
                x=todo.pop()
                for y in out[x]:
                    if y not in visited:
                        visited.add(y)
                        todo.append(y)
            closure.append(frozenset(visited))
        return tuple(closure)
    if task.family=="SUBSET":
        mask=1
        for weight in task.instance:
            mask|=mask<<weight
        return mask
    if task.family=="TEXT":
        return task.instance[0]
    raise ValueError("Unknown baseline family")

def strong_ask(task,context,query):
    if task.family=="GRAPH":
        src,dst=query
        return dst in context[src]
    if task.family=="SUBSET":
        return query>=0 and bool((context>>query)&1)
    if task.family=="TEXT":
        return query in context
    raise ValueError("Unknown baseline family")

def check_suite(tasks):
    ids=set()
    for t in tasks:
        if t.family not in FAMILIES or t.identifier in ids:
            raise ValueError("Duplicate or outside task family")
        ids.add(t.identifier)
        if not t.queries:raise ValueError("Task without objective")
        if t.family=="GRAPH":
            n,edges=t.instance
            if n!=18 or any(a<0 or b>=n or a>=n or b<0 for a,b in edges):
                raise ValueError("Bad graph instance")
            if any(not isinstance(q,tuple) or len(q)!=2 or
                   not 0<=q[0]<n or not 0<=q[1]<n for q in t.queries):
                raise ValueError("Bad graph query")
        elif t.family=="SUBSET":
            if len(t.instance)!=13 or any(not 1<=w<=32 for w in t.instance):
                raise ValueError("Unregistered sumset instance")
            if any(type(q) is not int or q<0 or q>1000 for q in t.queries):
                raise ValueError("Unregistered sumset query")
        else:
            text,=t.instance
            if len(text)!=900 or any(ch not in "abcdefghi" for ch in text):
                raise ValueError("Outside registered text distribution")
            if any(not 3<=len(q)<=5 or
                   any(ch not in "abcdefghi" for ch in q)
                   for q in t.queries):
                raise ValueError("Unregistered string query")
    return len(ids)
