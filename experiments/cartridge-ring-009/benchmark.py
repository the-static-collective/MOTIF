"""RING-009: evaluate frozen newly induced relational operator on NEW contrast.

This module is invoked in CI AFTER search.py has serialized the chosen
operator AST. It is the ONLY point where novel_pairs is imported.

Existing RING-008 program has a fair SAME-DATA comparison using identical
minimal-pair training examples; it also retains its original training-data
control. No candidate is reselected using postfreeze challenge labels.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import sys

import contrasts,induce,search
sys.path.insert(0,str(Path(__file__).resolve().parent.parent/"cartridge-ring-008"))
import engine,world

SCHEMA="motif.ring009.frozen-operator-transfer-trial.v1"

class HOLD(ValueError):
    pass


def original_ring008_spec():
    # Explicit frozen model from RING-008. It is NOT selected on this corpus.
    return {"ops":["char3","skip"],"decoder":"bayes",
            "binding":"factorized","margin":0.0,"overlap":2}


class AlwaysHold:
    def parse(self,text):
        from hashlib import sha256
        return {"status":"HOLD","frame":None,
                "raw_text_sha256":sha256(text.encode()).hexdigest()}


def verify_artifact(artifact):
    if (not isinstance(artifact,dict) or artifact.get("schema")!=search.SCHEMA
            or artifact.get("status")!=
            "ANTIUNIFICATION_GENERATED_NEW_RELATIONAL_OPERATOR_INSTANCES"
            or artifact.get("receipt_sha256")!=induce.digest({
                k:v for k,v in artifact.items() if k!="receipt_sha256"})
            or artifact.get("new_python_semantic_primitives_invented") is not False
            or artifact.get("heldout_labels_consulted") is not False
            or artifact.get("novel_test_module_imported_during_search") is not False
            or artifact.get("external_action_executed") is not False
            or artifact.get("authority")!="NONE"):
        raise HOLD("Unreviewed or evaluation-contaminated candidate program")
    program=induce.validate(artifact.get("program"))
    if program["source_training_sha256"]!=artifact.get("source_train_sha256"):
        raise HOLD("Program not derived from original training identity")
    train=contrasts.generate("train",seed=2026110901,repeats=4)
    dev=contrasts.generate("dev",seed=2026110902,repeats=4)
    if (train["receipt_sha256"]!=artifact["source_train_sha256"]
            or dev["receipt_sha256"]!=artifact["source_dev_sha256"]):
        raise HOLD("Original frozen source evidence not reproducible")
    # Even with re-hashed artifact, do not allow arbitrary altered rules to
    # masquerade as a learned hypothesis. Recompute the specified operator
    # induction from the *original data only*, never test labels.
    regenerated=induce.construct(train,**program["parameters"])
    if regenerated!=program:
        raise HOLD("Invented relational rules not reproducible from training")
    return train,program


def evaluate_frozen(artifact):
    train,program=verify_artifact(artifact)
    # The challenge module is imported only after source and rules are bound.
    import novel_pairs
    pairs_train=contrasts.flattened(train)
    reference_spec=original_ring008_spec()
    parsers={
        "induced_relational_operator":search.BoundDecoder(program),
        "ring008_feature_parser_same_training":engine.LearnedDecoder(
            pairs_train,reference_spec),
        "word_bayes_same_training":engine.LearnedDecoder(
            pairs_train,{
                "ops":["word"],"decoder":"bayes",
                "binding":"factorized","margin":0.04,"overlap":2,
            }),
        "ring008_original_source_training":engine.train(
            world.generate("train",seed=2026110801,rounds=5),
            reference_spec),
        "always_hold":AlwaysHold(),
    }
    trials=[]
    for seed in (2026110911,2026110912):
        source=novel_pairs.generate(seed=seed,repeats=3)
        examples=contrasts.flattened(source)
        measurements={
            name:engine.evaluate(parser,examples)
            for name,parser in parsers.items()
        }
        trials.append({
            "seed":seed,
            "source_sha256":source["receipt_sha256"],
            "case_count":len(examples),
            "contrast_pairs":len(source["pairs"]),
            "challenge_source_language_family":source["novel_phrase_family"],
            "models":measurements,
            "test_labels_not_used_in_model_selection":True,
            "source_was_written_by_same_experimenter":True,
        })
    counts={}
    for name in parsers:
        keys=trials[0]["models"][name]["metrics"].keys()
        counts[name]={k:sum(t["models"][name]["metrics"][k] for t in trials)
                      for k in keys}
    result={
        "schema":SCHEMA,
        "status":"AUTOGENERATED_RELATIONAL_OPERATOR_FAILED_OR_PASSED_POSTFREEZE_TEST",
        "frozen_program_sha256":artifact["receipt_sha256"],
        "program_source_operator_sha256":program["receipt_sha256"],
        "new_induced_operator_instances":program[
            "operator_instances_induced_from_examples"],
        "developer_original_logic_not_self_rewritten":True,
        "operator_rules_derived_by_antiunification_not_manually_written":True,
        "author_created_meaning_supervision_not_independent_annotation":True,
        "distinct_challenge_phrase_templates_not_seen_during_selection":True,
        "true_new_mathematical_primitives_discovered":False,
        "general_language_understanding_verified":False,
        "original_graph_and_tool_execution_authority":"NONE",
        "test_packets":trials,
        "combined":counts,
        "new_executable_or_network_capabilities_admitted":0,
        "external_actions_executed":False,
        "authority":"NONE",
    }
    result["receipt_sha256"]=induce.digest(result)
    return result


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--frozen",type=Path,required=True)
    p.add_argument("--out",type=Path)
    args=p.parse_args()
    try:
        data=json.loads(args.frozen.read_text())
        result=evaluate_frozen(data)
        if args.out:
            args.out.parent.mkdir(parents=True,exist_ok=True)
            args.out.write_text(json.dumps(result,sort_keys=True,indent=2)+"\n")
        print(json.dumps({
            "status":result["status"],
            "operator_instances":result["new_induced_operator_instances"],
            "tested":sum(p["case_count"] for p in result["test_packets"]),
            "comparisons":result["combined"],
            "receipt_sha256":result["receipt_sha256"],
        },sort_keys=True))
    except (HOLD,induce.HOLD,ValueError) as exc:
        print(json.dumps({"status":"HOLD","reason":str(exc)}))
        raise SystemExit(2)


if __name__=="__main__":
    main()
